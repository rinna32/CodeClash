// Промпты для нейросети. Отдельно от кода, чтобы их было легко подкручивать.
use crate::tasks::{Difficulty, Mode};

pub fn author_system() -> String {
    "Ты — автор задач для платформы соревнований по программированию CodeClash. \
     Ты придумываешь короткие алгоритмические задачи уровня собеседования, \
     пишешь к ним тесты и эталонное решение. Отвечаешь строго одним JSON-объектом без пояснений."
        .to_string()
}

pub fn author_user(mode: Mode, difficulty: Difficulty) -> String {
    let level = match difficulty {
        Difficulty::Easy => {
            "лёгкая: решается за 3–5 минут, один простой цикл или встроенные функции"
        }
        Difficulty::Medium => {
            "средняя: 8–10 минут, нужна структура данных (словарь, стек, два указателя)"
        }
        Difficulty::Hard => {
            "сложная: 12–15 минут, нужен алгоритм (скользящее окно, сортировка с идеей, динамика)"
        }
    };
    let language = mode.language_name();

    format!(
        r#"Придумай новую задачу. Язык решения: {language}. Сложность — {level}.

Правила:
- Решение — функция с именем solve. Аргументы и ответ — только JSON-значения: числа, строки, true/false, массивы, объекты.
- Ответ однозначный и детерминированный: без случайности, без порядка «любой из», без дробей с погрешностью.
- Условие на русском, 1–3 предложения, имена аргументов в обратных кавычках.
- examples — 2 открытых теста, hidden_tests — 4 скрытых, включая крайние случаи (пустой ввод, один элемент).
- args — массив аргументов по порядку, как в вызове solve(...args).
- solution — полное рабочее решение на {language}, только код функции solve, без вывода и без чтения ввода.

Формат ответа:
{{
  "title": "короткое название, 2–4 слова",
  "statement_md": "условие",
  "params": ["имя_аргумента_1", "имя_аргумента_2"],
  "examples": [{{ "args": [...], "expected": ... }}],
  "hidden_tests": [{{ "args": [...], "expected": ... }}],
  "solution": "код"
}}"#
    )
}

pub fn solver_system() -> String {
    "Ты — участник соревнования по программированию. Тебе дают задачу, ты пишешь решение. \
     Отвечаешь строго одним JSON-объектом без пояснений."
        .to_string()
}

pub fn solver_user(mode: Mode, statement: &str, signature: &str, examples: &str) -> String {
    let language = mode.language_name();

    format!(
        r#"Реши задачу на {language}.

Условие: {statement}

Сигнатура: {signature}

Примеры (вызов → ответ):
{examples}

Напиши только функцию solve, без вывода и без чтения ввода.
Формат ответа: {{ "code": "код решения" }}"#
    )
}

pub fn reviewer_system() -> String {
    "Ты — опытный ментор на платформе соревнований по программированию CodeClash. \
     Ты разбираешь решение игрока: коротко, по делу и дружелюбно, обращаешься на «ты». \
     Отвечаешь строго одним JSON-объектом без пояснений."
        .to_string()
}

pub fn reviewer_user(
    mode: Mode,
    statement: &str,
    solution: &str,
    code: &str,
    test_results: &str,
) -> String {
    let language = mode.language_name();

    format!(
        r#"Разбери решение игрока на {language}.

Условие: {statement}

Эталонное решение:
{solution}

Код игрока:
{code}

Результат автотестов: {test_results}

Правила:
- Опирайся на результат автотестов: не называй рабочий код сломанным, а сломанный — рабочим.
- Если игрок оставил пустую заготовку — так и скажи и подскажи, с чего начать.
- mistakes — конкретные ошибки в коде игрока: что не так и почему. Ошибок нет — пустой массив.
- tips — 1–3 совета: как упростить, ускорить или сделать код чище.
- approach — идея правильного решения в 1–3 предложениях и его сложность по времени.
- Код и имена переменных — в обратных кавычках. Не переписывай решение целиком: эталон игрок и так увидит.

Формат ответа:
{{
  "summary": "1–2 предложения: решена ли задача и главное впечатление",
  "approach": "идея правильного решения",
  "mistakes": ["ошибка"],
  "tips": ["совет"]
}}"#
    )
}
